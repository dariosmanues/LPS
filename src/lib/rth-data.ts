export function getRthCategoryColor(jenis: RthLocation['jenisRth'], nama?: string): {
  bg: string;
  border: string;
  badgeBg: string;
  badgeText: string;
  label: string;
} {
  if (jenis === 'Taman Kota') {
    return {
      bg: '#10b981',
      border: '#047857',
      badgeBg: '#d1fae5',
      badgeText: '#065f46',
      label: 'Taman Kota',
    };
  }
  if (jenis === 'Hutan Kota') {
    return {
      bg: '#047857',
      border: '#064e3b',
      badgeBg: '#a7f3d0',
      badgeText: '#064e3b',
      label: 'Hutan Kota',
    };
  }
  if (jenis === 'Kebun Bibit') {
    return {
      bg: '#0891b2',
      border: '#155e75',
      badgeBg: '#cffafe',
      badgeText: '#155e75',
      label: 'Kebun Bibit',
    };
  }
  const upperName = (nama || '').toUpperCase();
  if (upperName.startsWith('TUGU') || upperName.startsWith('BUNDARAN') || upperName.startsWith('SIMPANG')) {
    return {
      bg: '#d97706',
      border: '#92400e',
      badgeBg: '#fef3c7',
      badgeText: '#92400e',
      label: 'Tugu / Bundaran (Jalur Hijau)',
    };
  }
  return {
    bg: '#65a30d',
    border: '#3f6212',
    badgeBg: '#ecfccb',
    badgeText: '#3f6212',
    label: 'Jalur Hijau Di Jalan',
  };
}

